"""Dual RGB+segmentation output with normalized restored-structure transfer.

The pretrained RGB restorer is fixed in this component study. Its quality cannot
improve merely because the segmentation adapter/training protocol changes.
"""
from dataclasses import dataclass
from pathlib import Path

import torch
from torch import nn
import torch.nn.functional as F

from dehaze_seg.models.ColorAwareUnet import ColorAwareUNet
from dehaze_seg.models.joint import unpack_dehaze_output
from dehaze_seg.data.splits import file_digest
from scripts.vision_baseline_v1 import build_model as build_segmenter
from scripts.structure_visibility_v6 import gradients,structure_tensor

REPO=Path(__file__).resolve().parents[1]


@dataclass(frozen=True)
class Variant:
    geometry: str="none"
    support: str="positive"
    fog: str="random"


METHODS={
    "control":Variant(),
    "geometry":Variant("restored"),
    "support":Variant(support="risk"),
    "fog":Variant(fog="adversarial"),
    "geometry_support":Variant("restored","risk"),
    "geometry_fog":Variant("restored",fog="adversarial"),
    "support_fog":Variant(support="risk",fog="adversarial"),
    "full":Variant("restored","risk","adversarial"),
    "input_structure":Variant("input"),
    "negative_crops":Variant(support="crops"),
    "fog_unconstrained":Variant(fog="adversarial_free"),
    "cascade":Variant("cascade"),
}
FACTORIAL=tuple(list(METHODS)[:8])


class TensorAdapter(nn.Module):
    def __init__(self,channels=24):
        super().__init__();self.project=nn.Conv2d(channels,channels,1,bias=False)
        nn.init.zeros_(self.project.weight)

    def forward(self,feature,vector):
        dx,dy=gradients(feature.float())
        energy=dx.square()+dy.square()
        signal=(vector[:,0:1]*(dx.square()-dy.square())+2*vector[:,1:2]*dx*dy)/(energy+1e-6)
        bound=.25*(feature.float().square().mean((2,3),keepdim=True)+1e-6).sqrt().detach()
        return feature+(bound*torch.tanh(self.project(signal))).to(feature.dtype)


class PartialJoint(nn.Module):
    def __init__(self,dehazer,segmenter,variant):
        super().__init__();self.dehazer=dehazer.requires_grad_(False).eval()
        self.network=segmenter.network;self.variant=variant
        self.register_buffer("mean",segmenter.mean.clone());self.register_buffer("std",segmenter.std.clone())
        self.adapter=TensorAdapter()
        if variant.geometry in ("none","cascade"):
            self.adapter.requires_grad_(False)

    def train(self,mode=True):
        super().train(mode);self.dehazer.eval();return self

    def forward(self,image):
        # Input gradients are required by the training-only visibility ascent.
        # Frozen RGB parameters never receive gradients or optimizer updates.
        with torch.set_grad_enabled(torch.is_grad_enabled() and image.requires_grad):
            with torch.autocast(image.device.type,enabled=False):
                restored,_=unpack_dehaze_output(self.dehazer(image.float()))
        return self.forward_with_restored(image,restored)

    def forward_with_restored(self,image,restored):
        """Training acceleration: restored must be generated by the same fixedD.

        The ordinary inference forward never takes a clear reference as input.
        """
        raw=restored if self.variant.geometry=="cascade" else image
        feature=(raw-self.mean)/self.std
        vector=None
        if self.variant.geometry in ("restored","input"):
            vector,_=structure_tensor(restored if self.variant.geometry=="restored" else image)
        for name,block in self.network.backbone.items():
            feature=block(feature)
            if name=="3" and vector is not None:
                feature=self.adapter(feature,vector)
        logits=F.interpolate(self.network.classifier(feature),size=image.shape[-2:],mode="bilinear",align_corners=False)
        return restored,logits,{}


def dehazer_from_source(path):
    packet=torch.load(path,map_location="cpu",weights_only=True)
    config=packet["model_config"]["dehazer"]
    model=ColorAwareUNet(**config)
    model.load_state_dict({k[len("dehazer."):]:v for k,v in packet["model_state"].items() if k.startswith("dehazer.")},strict=True)
    return model.requires_grad_(False).eval(),config


def build_model(method,seed,dehazer,pretrained=True):
    segmenter=build_segmenter("deeplab_mobile_imagenet" if pretrained else "deeplab_mobile_scratch",seed)
    with torch.random.fork_rng(devices=[]):
        torch.manual_seed(seed+7_000_000)
        return PartialJoint(dehazer,segmenter,METHODS[method])


def load_model(path,device="cuda"):
    packet=torch.load(path,map_location="cpu",weights_only=True)
    if packet["format"] not in ("partial-joint-v7","partial-joint-v7-portable"):
        raise ValueError("Unsupported partial joint checkpoint")
    if packet["format"].endswith("portable"):
        dehazer=ColorAwareUNet(**packet["dehazer_config"])
        dehazer.load_state_dict(packet["dehazer_state"],strict=True)
    else:
        source=Path(packet["dehazer_source"])
        if file_digest(source)!=packet["dehazer_source_sha256"]:
            raise ValueError("Fixed RGB checkpoint changed")
        dehazer,_=dehazer_from_source(source)
    model=build_model(packet["method"],packet["seed"],dehazer,pretrained=False)
    expected={k for k in model.state_dict() if not k.startswith("dehazer.")}
    if set(packet["segmentation_state"])!=expected:
        raise ValueError("Segmentation checkpoint keys differ")
    state=model.state_dict();state.update(packet["segmentation_state"]);model.load_state_dict(state,strict=True)
    return model.to(device).eval(),packet


def partial_segmentation_loss(logits,target):
    """Unknown255 contributes neither a CE nor a Dice gradient."""
    valid=target!=255
    if not bool(valid.any()):
        raise ValueError("No supervised pixels")
    ce=F.cross_entropy(logits,target,ignore_index=255,reduction="sum")/valid.sum()
    probabilities=logits.float().softmax(1)*valid[:,None]
    onehot=F.one_hot(target.clamp(0,1),2).permute(0,3,1,2).float()*valid[:,None]
    intersection=(probabilities*onehot).sum((0,2,3))
    denominator=(probabilities+onehot).sum((0,2,3))
    return ce+1-((2*intersection+1e-6)/(denominator+1e-6)).mean()
